/**
 * gen-icons.mjs
 * Reads selected pixelarticons SVGs and generates
 * internal/server/view/shared_icons_neo.go, and compiles the line icon
 * sources in internal/server/view/icons/*.svg into shared_icons_line.go.
 *
 * Run: node gen-icons.mjs  (from editor/)
 * Or:  make icons
 */

import { readFileSync, readdirSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dir   = dirname(fileURLToPath(import.meta.url));
const SVG_DIR = resolve(__dir, 'node_modules/pixelarticons/svg');
const OUT     = resolve(__dir, '../internal/server/view/shared_icons_neo.go');

// pixelarticons filename (no .svg)  →  Go constant suffix
const ICONS = [
  ['home',         'Home'],
  ['notes',        'Library'],
  ['image',        'Images'],
  ['message',      'Agent'],
  ['settings-cog-2', 'Settings'],
  ['search',       'Search'],
  ['bookmark',     'Bookmark'],
  ['reload',       'Reload'],
  ['file-text',    'FileText'],
  ['folder',       'Folder'],
  ['note',         'Note'],
  ['upload',       'Upload'],
  ['globe',        'Globe'],
  ['plus',         'Plus'],
  ['check',        'Check'],
  ['delete',       'Delete'],
  ['cancel',       'Cancel'],
  ['zap',          'Zap'],
];

function clean(raw) {
  let s = raw.trim();
  // strip xmlns, width, height attrs from outer <svg> tag
  s = s.replace(/\s+xmlns="[^"]*"/g, '');
  s = s.replace(/\s+width="\d+"/g, '');
  s = s.replace(/\s+height="\d+"/g, '');
  // strip <defs>…</defs> blocks (clip-path defs that are just full-rect no-ops)
  s = s.replace(/\s*<defs>[\s\S]*?<\/defs>/g, '');
  // strip clip-path="url(#…)" attributes left on <g> tags
  s = s.replace(/\s+clip-path="url\([^)]*\)"/g, '');
  // unwrap empty <g> tags: <g>\n  paths\n</g> → paths
  s = s.replace(/<g>\n([\s\S]*?)\n<\/g>/g, (_, inner) => inner);
  return s;
}

const lines = [
  'package view',
  '',
  '// Code generated by editor/gen-icons.mjs — DO NOT EDIT.',
  '// Run `make icons` to regenerate.',
  '',
];

let ok = 0, skip = 0;
for (const [file, suffix] of ICONS) {
  const path = resolve(SVG_DIR, `${file}.svg`);
  let raw;
  try {
    raw = readFileSync(path, 'utf8');
  } catch {
    console.warn(`  SKIP  ${file}.svg — not found`);
    skip++;
    continue;
  }
  const svg = clean(raw);
  lines.push(`// svgPx${suffix} is the pixelarticons "${file}" icon.`);
  lines.push(`const svgPx${suffix} = \`` + svg + `\``);
  lines.push('');
  console.log(`  OK    ${file}.svg → svgPx${suffix}`);
  ok++;
}

writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`\nGenerated ${ok} icons (${skip} skipped) → ${OUT}`);

// ── Line icons ──────────────────────────────────────────────────────────────
// Each source is a plain 24×24 SVG in Lucide coordinates. Its root carries
// data-base (the Lucide icon it starts from), data-zoom (optical scale about
// the centre, applied at render), data-kind="glyph" for small UI marks
// (chevrons, close) and, if altered, data-changes.
const LINE_DIR = resolve(__dir, '../internal/server/view/icons');
const LINE_OUT = resolve(__dir, '../internal/server/view/shared_icons_line.go');

function attr(tag, name) {
  const m = tag.match(new RegExp(`\\s${name}="([^"]*)"`));
  return m ? m[1] : '';
}

const line = [
  'package view',
  '',
  '// Code generated by editor/gen-icons.mjs from icons/*.svg — DO NOT EDIT.',
  '// Run `make icons` to regenerate.',
  '',
  'var lineIcons = map[string]lineIconDef{',
];
const names = readdirSync(LINE_DIR).filter((f) => f.endsWith('.svg')).sort();
for (const file of names) {
  const name = file.slice(0, -4);
  const raw = readFileSync(resolve(LINE_DIR, file), 'utf8');
  const open = raw.match(/<svg\b[^>]*>/);
  const body = raw.match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/);
  if (!open || !body) throw new Error(`${file}: no <svg> root`);
  if (attr(open[0], 'viewBox') !== '0 0 24 24') throw new Error(`${file}: viewBox must be 0 0 24 24`);
  const base = attr(open[0], 'data-base');
  if (!base) throw new Error(`${file}: missing data-base`);
  const zoom = Number(attr(open[0], 'data-zoom') || '1');
  if (!(zoom >= 1 && zoom <= 1.5)) throw new Error(`${file}: data-zoom out of range`);
  const paths = body[1].trim().split(/\n\s*/).join('');
  if (paths.includes('`')) throw new Error(`${file}: backtick in paths`);
  const kind = attr(open[0], 'data-kind');
  if (kind && kind !== 'glyph') throw new Error(`${file}: data-kind must be "glyph" or absent`);
  line.push(`\t${JSON.stringify(name)}: {Paths: \`${paths}\`, Zoom: ${zoom}, Glyph: ${kind === 'glyph'}, Base: ${JSON.stringify(base)}, Changes: ${JSON.stringify(attr(open[0], 'data-changes'))}},`);
  console.log(`  OK    icons/${file}`);
}
line.push('}', '');
writeFileSync(LINE_OUT, line.join('\n'), 'utf8');
console.log(`\nGenerated ${names.length} line icons → ${LINE_OUT}`);
